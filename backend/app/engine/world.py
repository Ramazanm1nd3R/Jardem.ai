"""Mutable operational state: departments, units, incidents, messages."""

from __future__ import annotations

from dataclasses import dataclass, field

from app.domain.geo import LatLon
from app.domain.models import IncidentStatus, Priority, Service, UnitStatus
from app.domain.routing import Maneuver


@dataclass(slots=True)
class Department:
    id: str
    service: Service
    name: str
    address: str
    lat: float
    lon: float
    approximate: bool = False  # location is not a surveyed OSM object


@dataclass(slots=True)
class CrewMember:
    id: str
    name: str
    role: str
    phone: str = ""
    lead: bool = False


@dataclass(slots=True)
class RouteState:
    """A unit's current drive: the planned path and how far along it the unit is."""

    target: str  # "incident" | "base"
    edges: tuple[int, ...]
    geometry: tuple[LatLon, ...]
    distance_m: float
    maneuvers: tuple[Maneuver, ...]
    costs_version: int
    edge_index: int = 0
    edge_offset_m: float = 0.0
    travelled_m: float = 0.0

    @property
    def finished(self) -> bool:
        return self.edge_index >= len(self.edges)


@dataclass(slots=True)
class Unit:
    id: str
    department_id: str
    service: Service
    kind: str
    name: str  # as shown to citizens, e.g. "Подстанция №7"
    callsign: str  # as used by crews and dispatch, e.g. "СМП №7"
    capabilities: frozenset[str]
    status: UnitStatus
    lat: float
    lon: float
    base: LatLon
    plate: str = ""
    vehicle: str = ""
    fuel_pct: int = 100
    crew: list[CrewMember] = field(default_factory=list)
    equipment: list[dict] = field(default_factory=list)
    heading: float = 0.0
    incident_id: str | None = None
    reassignments: int = 0
    route: RouteState | None = None
    controlled_by: str | None = None  # responder account driving this unit by hand
    status_since: float = 0.0
    shift_started_at: float | None = None
    device_gps_at: float = -1e18  # sim time of the last real GPS fix from the app


@dataclass(slots=True)
class TimelineEntry:
    status: str
    at: float  # wall-clock unix seconds
    note: str = ""


@dataclass(slots=True)
class Incident:
    id: str
    number: int
    service: Service
    category: str
    priority: Priority
    required: frozenset[str]
    units_required: int
    lat: float
    lon: float
    address: str
    description: str
    status: IncidentStatus
    created_at: float  # sim time, drives the planner
    created_wall: float  # wall-clock time, shown to people
    citizen_id: str | None = None
    caller_name: str = ""
    caller_phone: str = ""
    extra_info: str = ""
    synthetic: bool = False  # generated by the demo traffic of calls, not by a person
    unit_ids: list[str] = field(default_factory=list)
    served_by: list[str] = field(default_factory=list)  # every unit that reached the scene
    timeline: list[TimelineEntry] = field(default_factory=list)
    triage: dict | None = None
    first_arrival_s: float | None = None  # sim seconds from creation to first unit on scene
    closed_wall: float | None = None
    on_scene_until: float | None = None  # sim time when simulated crews finish


@dataclass(slots=True)
class Message:
    id: str
    unit_id: str
    sender: str  # "dispatcher" | "unit"
    author: str
    text: str
    at: float  # wall-clock


@dataclass(slots=True)
class World:
    departments: dict[str, Department] = field(default_factory=dict)
    units: dict[str, Unit] = field(default_factory=dict)
    incidents: dict[str, Incident] = field(default_factory=dict)
    messages: list[Message] = field(default_factory=list)
    next_incident_number: int = 45821

    def units_of(self, incident: Incident) -> list[Unit]:
        return [self.units[u] for u in incident.unit_ids if u in self.units]
